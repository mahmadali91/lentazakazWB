      <div class="faq">
        <details><summary>Через сколько появляются новые заказы?</summary><p>В течение 5 минут после оформления — сервис забирает ленту из WB каждые 5 минут. Если WB временно ограничит запросы, сервис подождёт и продолжит сам.</p></details>
